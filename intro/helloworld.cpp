#include<iostream>

int main(){
    // to write a comment you should  use two slashes and the compiler ignors the comment :)
    /*
    for multiline comments like docstrings in python, 
    a slash and asterisk followed by comment and at the 
    end astrix and slash to end the multiline comment.
    */
    std::cout << "Hello World!" << std::endl;
    std::cout << "I like any kind of food :)" << std::endl;
    std::cout << "it's not a problem, if you do not like any specific food more than the others!!" << std::endl; // new comment here!
    std::cout << "backslash n  is the same as <<std::endl which means both do the same job (going to the next line)." << "\n";
    return 0;
}
